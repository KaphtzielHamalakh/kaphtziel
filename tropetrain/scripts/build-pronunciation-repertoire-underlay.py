"""Reproduce source syllable facts for the separately pinned reader books.

The same unmodified upstream computation must reproduce both literal styles.
Reader Hebrew, source display packets, alternatives and stress remain untouched.
Rows that cannot be reproduced remain explicitly unassigned, never approximated.
"""
from pathlib import Path
import hashlib,importlib.util,json,sys,tempfile,zipfile

ROOT=Path(__file__).resolve().parent.parent
spec=importlib.util.spec_from_file_location('source_underlay',ROOT/'scripts/build-pronunciation-underlay.py')
core=importlib.util.module_from_spec(spec);spec.loader.exec_module(core)
verify='--check' in sys.argv
summary=json.loads((ROOT/'pronunciation-repertoire-summary.js').read_text().split('export const PRONUNCIATION_REPERTOIRE_SUMMARY=')[1].strip().removesuffix(';'))
books=[]
with tempfile.TemporaryDirectory(prefix='tropetrain-repertoire-underlay-') as temporary:
    target=Path(temporary)
    with zipfile.ZipFile(core.ARCHIVE) as archive:
        manifest=json.loads(archive.read('MANIFEST.json'));assert manifest['commit']==core.COMMIT
        allowed={entry['path']:entry for entry in manifest['files']}
        assert set(archive.namelist())==set(allowed)|{'MANIFEST.json','NOTICE.txt'}
        for name,entry in allowed.items():
            assert not Path(name).is_absolute() and '..' not in Path(name).parts
            content=archive.read(name)
            assert len(content)==entry['bytes'] and core.digest(content)==entry['sha256']
            assert hashlib.sha1(b'blob '+str(len(content)).encode()+b'\0'+content).hexdigest()==entry['gitBlob']
            path=target/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(content)
    sys.path.insert(0,str(target/'py'));sys.dont_write_bytecode=True
    from phonetic_mam import analysis_reader
    from phonetic_mam.core import jtech_ascii
    for book in summary['books']:
        bid=book['bookId'];source=ROOT/f'data/pronunciation/repertoire/{bid}.json.gz'
        assert core.digest(source.read_bytes())==book['packetSha256']
        # A private per-book audit lets the shared computation remain identical;
        # the public combined record retains every result and unresolved row.
        audit_path=target/(bid+'-audit.json')
        published=ROOT/f'data/pronunciation/repertoire-underlay/{bid}.json.gz'
        destination=target/(bid+'.json.gz') if verify else published
        report=core.build(analysis_reader,jtech_ascii,source=source,
            destination=destination,
            audit_path=audit_path,verify=False,emit=False)
        assert report['groups']==book['groups']
        if verify:
            assert published.read_bytes()==destination.read_bytes(),bid+' underlay differs'
        books.append({'bookId':bid,**report})
        print(json.dumps({'bookId':bid,'groups':report['groups'],'units':report['counts'].get('variantUnits',0),'unresolvedRows':len(report['unresolved']),'bytes':report['outputBytes']}),flush=True)

audit={'schema':'tropetrain-pronunciation-repertoire-underlay-v1','revision':1,
    'sourceCommit':core.COMMIT,'license':'CC-BY-SA-4.0',
    'computationSource':'assets/pronunciation/phonetic-mam-computation-sources.zip',
    'computationSourceSha256':core.digest(core.ARCHIVE.read_bytes()),
    'books':books,'groups':sum(b['groups'] for b in books),
    'unresolvedRows':sum(len(b['unresolved']) for b in books),
    'method':'The pinned source computation must reproduce both complete published transcription styles and joins for each Hebrew alternative. Reader cluster ranges require exact written letters and consensus across alternatives. Different written/read forms and computation failures retain explicit gaps. No source text, accent, stress or prior word link is rewritten.',
    'limits':'Computed source syllable correspondence, not independent linguistic/cantorial review. No inferred phonemes, category/IPA plan, musical note allocation, recording intervals, new singing voice or Kinnor phonological grammar.'}
compact={'sourceCommit':core.COMMIT,'computationSourceSha256':audit['computationSourceSha256'],
    'books':[{'bookId':b['bookId'],'inputSha256':b['inputSha256'],'packetSha256':b['outputSha256'],'packetBytes':b['outputBytes'],'groups':b['groups'],'unresolvedRows':len(b['unresolved'])} for b in books]}
outputs={'docs/PRONUNCIATION-REPERTOIRE-UNDERLAY.json':json.dumps(audit,ensure_ascii=False,indent=2)+'\n',
    'pronunciation-repertoire-underlay-summary.js':'// Generated by scripts/build-pronunciation-repertoire-underlay.py.\nexport const PRONUNCIATION_REPERTOIRE_UNDERLAY='+json.dumps(compact,separators=(',',':'))+';\n'}
for name,text in outputs.items():
    if verify:assert (ROOT/name).read_text()==text,name+' differs'
    else:(ROOT/name).write_text(text)
print(json.dumps({'books':len(books),'groups':audit['groups'],'unresolvedRows':audit['unresolvedRows']}),flush=True)
